// itemCategoryLabel 返回品类中文名；表里没有的品类返回空串。
func itemCategoryLabel(category int64) string {
	return itemCategoryLabels[category]
}

// itemCategoryText 返回「12 鱼钩」这种展示串，未知品类只返回数字。
func itemCategoryText(category int64) string {
	if label := itemCategoryLabel(category); label != "" {
		return fmt.Sprintf("%d %s", category, label)
	}
	return fmt.Sprintf("%d", category)
}
