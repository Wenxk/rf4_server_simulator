-- 昼夜曲线：四段权重（夜 20-05、晨 05-09、昼 09-16、昏 16-20），
-- 空串表示该鱼只有旧版 diel_mask 位图，调用方回退到「命中 1.0 / 未命中 0.35」。
--
-- 为什么不再用「位图 + 段数折算加成」：
--   位图只能表达「开 / 关」两档，峰值时段最容易出、过了峰值逐渐变少但仍会出，
--   这种窗口期表达不出来；同一时段的所有鱼要么满权重、要么统一降到惩罚值，
--   鱼种之间没有差异。曲线是乘性权重（峰值 1.0，最低 0.08），按段取系数即可。
--
-- 曲线顺序固定为 [夜, 晨, 昼, 昏]，与 worldclock 的位序
-- （1 夜 / 2 晨 / 4 昼 / 8 昏）严格对应，也是上游资产 fish_ecology_defs.json
-- 的编码顺序。资产由 ensureFishEcology 在启动时按 profile_version 刷进本列。
